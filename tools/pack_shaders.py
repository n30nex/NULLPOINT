"""Build embedded shader data with Windows' system MSZIP codec; no packages."""
from pathlib import Path
import ctypes as c
import re

root = Path(__file__).resolve().parent.parent
source = (root / "shaders.glsl").read_text(encoding="utf-8")
chunks = re.findall(r"(?ms)^// @shader (\w+)\s*\n(.*?)(?=^// @shader |\Z)", source)
assert [name for name, _ in chunks] == ["sceneVS", "sceneFS", "postVS", "postFS", "bloomFS"]
raw, offsets = bytearray(), []
for name, text in chunks:
    offsets.append((name, len(raw)))
    # Keep preprocessor newlines; remove comments and excess whitespace only.
    text = re.sub(r"//[^\n]*", "", text).strip()
    text = "\n".join(re.sub(r"[ \t]+", " ", line).strip() for line in text.splitlines())
    raw.extend(text.encode("utf-8") + b"\0")

api = c.WinDLL("cabinet", use_last_error=True)
api.CreateCompressor.argtypes = [c.c_uint, c.c_void_p, c.POINTER(c.c_void_p)]
api.Compress.argtypes = [c.c_void_p, c.c_void_p, c.c_size_t, c.c_void_p, c.c_size_t, c.POINTER(c.c_size_t)]
api.CloseCompressor.argtypes = [c.c_void_p]
handle, count = c.c_void_p(), c.c_size_t()
if not api.CreateCompressor(2, None, c.byref(handle)):
    raise c.WinError(c.get_last_error())
try:
    buf = c.create_string_buffer(bytes(raw))
    api.Compress(handle, buf, len(raw), None, 0, c.byref(count))
    if c.get_last_error() != 122 or count.value == 0:
        raise c.WinError(c.get_last_error())
    packed = c.create_string_buffer(count.value)
    if not api.Compress(handle, buf, len(raw), packed, len(packed), c.byref(count)):
        raise c.WinError(c.get_last_error())
finally:
    api.CloseCompressor(handle)

api.CreateDecompressor.argtypes = api.CreateCompressor.argtypes
api.Decompress.argtypes = api.Compress.argtypes
api.CloseDecompressor.argtypes = [c.c_void_p]
decoded, decoded_size = c.create_string_buffer(len(raw)), c.c_size_t()
if not api.CreateDecompressor(2, None, c.byref(handle)):
    raise c.WinError(c.get_last_error())
try:
    if not api.Decompress(handle, packed, count.value, decoded, len(raw), c.byref(decoded_size)):
        raise c.WinError(c.get_last_error())
    if decoded_size.value != len(raw) or decoded.raw != bytes(raw):
        raise ValueError("Shader compression round trip failed")
finally:
    api.CloseDecompressor(handle)

header = f"/* Generated by tools/pack_shaders.py. Edit shaders.glsl instead. */\nstatic char shaderText[{len(raw)}];\n"
header += "static const unsigned char shaderPack[]={" + ",".join(map(str, packed.raw[:count.value])) + "};\n"
header += "".join(f"#define {name} (shaderText+{offset})\n" for name, offset in offsets)
(root / "build").mkdir(exist_ok=True)
(root / "build" / "shaders.h").write_text(header, encoding="ascii")
print(f"Shader data: {len(raw)} -> {count.value} bytes")
